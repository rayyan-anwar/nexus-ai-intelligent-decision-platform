"""Train on the bundled SYNTHETIC sample and write docs/results.md from the actual run.

Usage: PYTHONPATH=backend python scripts/generate_results.py
Every number in the output is computed by this script; nothing is typed in by hand.
"""

import platform
import time
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.metrics import roc_auc_score

from app import __version__
from app.ml import accel
from app.ml.anomaly import detect_anomalies
from app.ml.drift import analyze_drift
from app.ml.ingest import read_stored_csv
from app.ml.pipeline import TrainConfig, apply_plan, split_indices, train_experiment
from app.ml.schema import plan_features
from app.ml.tracking import software_versions

ROOT = Path(__file__).resolve().parents[1]
SAMPLE = ROOT / "data" / "sample"
SEED = 42
DROP = {"churned": ["risk_tier", "monthly_spend"], "risk_tier": ["churned", "monthly_spend"], "monthly_spend": ["churned", "risk_tier"]}


def f(v, nd=3):
    return "n/a" if v is None else f"{v:.{nd}f}"


def main() -> None:
    df = read_stored_csv(SAMPLE / "nexus_synthetic_accounts.csv")
    truth = pd.read_csv(SAMPLE / "anomaly_ground_truth.csv")
    out: list[str] = []
    sv = software_versions()
    out += [
        "# Results from actual runs on the SYNTHETIC sample\n",
        f"Generated by `scripts/generate_results.py` (NEXUS {__version__}, seed {SEED}). Environment: Python {sv['python']}, "
        f"scikit-learn {sv['scikit_learn']}, pandas {sv['pandas']}, numpy {sv['numpy']}, {platform.machine()}.\n",
        "> **Read this first.** The data is synthetic and its relationships were written into the generator. "
        "These numbers demonstrate that the pipeline works and is evaluated honestly; they say nothing about performance on real data. "
        "Each result comes from a single random split and carries sampling uncertainty.\n",
    ]
    for target, drop in DROP.items():
        frame = df.drop(columns=drop)
        t0 = time.perf_counter()
        res = train_experiment(frame, TrainConfig(target=target, seed=SEED))
        secs = time.perf_counter() - t0
        s = res.summary
        spec = s["primary_metric"]
        keys = ["rmse", "mae", "r2"] if s["task"] == "regression" else ["roc_auc", "pr_auc", "f1", "f1_macro", "accuracy"]
        keys = [k for k in keys if any(c["validation"].get(k) is not None for c in s["candidates"])]
        out.append(f"\n## Target `{target}` ({s['task']})\n")
        out.append(f"Rows used {s['rows_used']} (train {s['split']['n_train']} / validation {s['split']['n_validation']} / test {s['split']['n_test']}). "
                   f"Selection metric: **{spec['name']}** ({spec['direction']} is better), computed on the validation split. Training time {secs:.1f}s.\n")
        out.append("| Model | " + " | ".join(f"val {k}" for k in keys) + " |")
        out.append("|---|" + "---:|" * len(keys))
        for c in s["candidates"]:
            mark = " **(selected)**" if c["selected"] else ""
            out.append(f"| {c['name']}{mark} | " + " | ".join(f(c["validation"].get(k)) for k in keys) + " |")
        b = s["baseline"]
        out.append(f"| {b['name']} | " + " | ".join(f(b["validation"].get(k)) for k in keys) + " |")
        out.append("\n| Held-out test | " + " | ".join(keys) + " |")
        out.append("|---|" + "---:|" * len(keys))
        out.append(f"| {s['selected_model']} | " + " | ".join(f(s["test_metrics"].get(k)) for k in keys) + " |")
        out.append(f"| {b['name']} | " + " | ".join(f(b["test"].get(k)) for k in keys) + " |")
        top = ", ".join(f"{i['feature']} ({i['importance']:.3f}{', unstable' if i['unstable'] else ''})" for i in s["importance"][:5])
        out.append(f"\nTop permutation importances (validation): {top}.\n")
        if s["warnings"]:
            out.append("Warnings raised: " + "; ".join(s["warnings"]) + "\n")

        # ---- error analysis ----
        if s["task"] == "regression":
            work = frame.reset_index(drop=True)
            plan, _ = plan_features(work, target)
            X = apply_plan(work, plan)
            y = work[target].astype(float)
            _, _, te = split_indices(y, "regression", SEED, 0.2, 0.2)
            pred = res.bundle.pipeline.predict(X.iloc[te])
            err = y.iloc[te].to_numpy() - pred
            is_anom = truth["is_injected_anomaly"].to_numpy()[te]
            out.append("**Error analysis.** Test RMSE overall "
                       f"{np.sqrt(np.mean(err**2)):.2f}; excluding the {int(is_anom.sum())} injected-anomaly rows in the test split "
                       f"{np.sqrt(np.mean(err[~is_anom]**2)):.2f}. A handful of extreme records dominate squared error, so report MAE and RMSE together.\n")
        elif s["task"] == "binary":
            cm = s["test_metrics"]["confusion_matrix"]
            prec, rec = s["test_metrics"]["precision"], s["test_metrics"]["recall"]
            n_pos = sum(cm["matrix"][cm["labels"].index(s["positive_label"])])
            if rec < prec:
                reading = f"recall ({rec:.3f}) is below precision ({prec:.3f}): at the default 0.5 decision threshold the model misses most positives. Threshold tuning is not implemented."
            else:
                reading = f"recall ({rec:.3f}) is at least as high as precision ({prec:.3f}), i.e. the model favours catching positives over avoiding false alarms."
            out.append(f"**Error analysis.** Test confusion matrix (rows = true, columns = predicted, labels {cm['labels']}): {cm['matrix']}. "
                       f"Positive class `{s['positive_label']}` has only {n_pos} test rows, so metrics are noisy. Here {reading}\n")
        else:
            pcs = ", ".join(f"{p['label']}: recall {p['recall']:.2f} (n={p['support']})" for p in s["test_metrics"]["per_class"])
            text = f"**Error analysis.** Per-class test recall: {pcs}."
            cm = s["test_metrics"]["confusion_matrix"]
            if set(cm["labels"]) == {"low", "medium", "high"}:
                m = np.array(cm["matrix"]); ix = {l: i for i, l in enumerate(cm["labels"])}
                errors = int(m.sum() - np.trace(m))
                far = int(m[ix["low"], ix["high"]] + m[ix["high"], ix["low"]])
                text += f" Of {errors} misclassified test rows, {far} are between the two extreme classes (low vs high); the rest involve `medium`."
            out.append(text + "\n")

        gap = (s["test_metrics"].get(spec["name"]) or 0) - (next(c for c in s["candidates"] if c["selected"])["validation"].get(spec["name"]) or 0)
        out.append(f"**Validation vs test.** The selected model's {spec['name']} changed by {gap:+.3f} from validation to the held-out test split. "
                   "Part of any gap comes from noise in small splits and from choosing the best of several models on validation; treat both numbers as rough.\n")

    feat = df.drop(columns=["churned", "risk_tier"])
    an = detect_anomalies(feat, sensitivity="medium", seed=SEED)
    y = truth["is_injected_anomaly"].to_numpy()
    k = int(y.sum())
    top_k = np.argsort(-np.asarray(an["scores"]))[:k]
    out.append("\n## Anomaly detection (Isolation Forest)\n")
    out.append(f"Injected anomalies: {k} of {len(y)}. ROC-AUC of anomaly score vs injected label: **{roc_auc_score(y, an['scores']):.3f}**; "
               f"precision@{k}: **{y[top_k].mean():.3f}**; random baseline precision {y.mean():.3f}. "
               f"At sensitivity 'medium' the detector flags {an['n_flagged']} rows ({100 * an['n_flagged'] / len(y):.1f}%).\n")
    out.append("Injected anomalies are extreme by construction, so real-world detection will be harder.\n")

    shifted = pd.read_csv(SAMPLE / "fixtures" / "drift_current.csv")
    dr = analyze_drift(df, shifted)
    same = analyze_drift(df, df.sample(600, random_state=1))
    out.append("\n## Drift detection\n")
    out.append(f"Shifted fixture vs reference: dataset drift = **{dr['dataset_drift']}**, {dr['columns_drifted']} of {dr['columns_analyzed']} columns flagged.\n")
    out.append("| Column | PSI | level | adjusted p |\n|---|---:|---|---:|")
    for c in dr["columns"][:8]:
        out.append(f"| {c['column']} | {f(c['psi'])} | {c['level']} | {f(c.get('p_value_adjusted'), 4)} |")
    out.append(f"\nControl (random resample of the reference): dataset drift = **{same['dataset_drift']}**, {same['columns_drifted']} column(s) flagged.\n")
    out.append(f"\nNative accelerator used for binning/statistics: {accel.native_available()}.\n")
    (ROOT / "docs" / "results.md").write_text("\n".join(out), encoding="utf-8")
    print("wrote docs/results.md")


if __name__ == "__main__":
    main()
