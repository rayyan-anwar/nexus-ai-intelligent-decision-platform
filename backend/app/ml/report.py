"""Self-contained HTML experiment report. All dynamic text is HTML-escaped."""

from __future__ import annotations

from html import escape
from typing import Any

CSS = """
body{font-family:system-ui,-apple-system,Segoe UI,Roboto,sans-serif;margin:0;color:#1b2430;background:#f6f8fa}
main{max-width:920px;margin:0 auto;padding:24px}
h1{margin-bottom:4px} h2{margin-top:32px;border-bottom:1px solid #d0d7de;padding-bottom:6px}
table{border-collapse:collapse;width:100%;background:#fff;font-size:14px}
th,td{border:1px solid #d0d7de;padding:6px 10px;text-align:left} th{background:#eef2f6}
.warn{background:#fff8e1;border-left:4px solid #f0ad00;padding:8px 12px;margin:8px 0}
.bar{background:#2f6feb;height:12px;border-radius:3px}.muted{color:#57606a;font-size:13px}
"""


def _fmt(v: Any) -> str:
    if v is None:
        return "n/a"
    if isinstance(v, float):
        return f"{v:.4g}"
    return escape(str(v))


def _table(headers: list[str], rows: list[list[Any]]) -> str:
    head = "".join(f"<th>{escape(h)}</th>" for h in headers)
    body = "".join("<tr>" + "".join(f"<td>{_fmt(c)}</td>" for c in r) + "</tr>" for r in rows)
    return f"<table><thead><tr>{head}</tr></thead><tbody>{body}</tbody></table>"


def _scalar_metrics(m: dict) -> dict:
    return {k: v for k, v in m.items() if isinstance(v, (int, float)) or v is None}


def render_html_report(experiment: dict[str, Any], summary: dict[str, Any], *, dataset_name: str = "dataset") -> str:
    task = summary["task"]
    spec = summary["primary_metric"]
    metric_keys = (
        ["accuracy", "precision", "recall", "f1", "f1_macro", "roc_auc", "pr_auc"]
        if task != "regression" else ["mae", "rmse", "r2"]
    )
    rows = []
    for c in summary["candidates"]:
        rows.append([c["name"] + (" (selected)" if c.get("selected") else "")] + [c["validation"].get(k) for k in metric_keys])
    base = summary["baseline"]
    rows.append([base["name"] + " (baseline)"] + [base["validation"].get(k) for k in metric_keys])
    test = summary["test_metrics"]
    base_test = summary["baseline"]["test"]
    imp = summary["importance"][:15]
    top = max([abs(i["importance"]) for i in imp] + [1e-12])
    imp_rows = "".join(
        f"<tr><td>{escape(i['feature'])}</td><td>{_fmt(i['importance'])}</td>"
        f"<td style='width:40%'><div class='bar' style='width:{max(0.0, i['importance']) / top * 100:.0f}%'></div></td>"
        f"<td>{'unstable' if i.get('unstable') else ''}</td></tr>"
        for i in imp
    )
    warnings = "".join(f"<div class='warn'>{escape(w)}</div>" for w in summary["warnings"] + summary["explanation_warnings"])
    limits = "".join(f"<li>{escape(x)}</li>" for x in summary["limitations"])
    rec = summary["experiment_record"]
    split = summary["split"]
    return f"""<!doctype html><html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1"><title>NEXUS AI report - {escape(str(experiment.get('id', '')))}</title>
<style>{CSS}</style></head><body><main>
<h1>NEXUS AI experiment report</h1>
<p class="muted">Experiment {escape(str(experiment.get('id', '')))} &middot; dataset {escape(dataset_name)} &middot;
target <b>{escape(summary['target'])}</b> &middot; task {escape(task)} &middot; seed {escape(str(summary['seed']))}</p>
<h2>Summary</h2>
<p>Selected model: <b>{escape(summary['selected_model'])}</b>, chosen on the validation split using
<b>{escape(spec['name'])}</b> ({escape(spec['direction'])} is better). The test split was evaluated once, after selection.</p>
{_table(['Split', 'Rows'], [['train', split['n_train']], ['validation', split['n_validation']], ['test', split['n_test']]])}
<h2>Model comparison (validation split)</h2>
{_table(['Model'] + metric_keys, rows)}
<h2>Held-out test metrics</h2>
{_table(['Metric', 'Selected model', 'Baseline'], [[k, test.get(k), base_test.get(k)] for k in metric_keys])}
<h2>Feature importance</h2>
<p class="muted">Permutation importance on the validation split. Describes the model, not causes.</p>
<table><thead><tr><th>Feature</th><th>Importance</th><th></th><th></th></tr></thead><tbody>{imp_rows}</tbody></table>
<h2>Warnings</h2>{warnings or '<p>None.</p>'}
<h2>Limitations</h2><ul>{limits}</ul>
<h2>Reproducibility</h2>
{_table(['Item', 'Value'], [['dataset fingerprint (sha256)', rec.get('dataset_fingerprint')], ['trained at', rec.get('trained_at')],
 ['python', rec['software'].get('python')], ['scikit-learn', rec['software'].get('scikit_learn')],
 ['pandas', rec['software'].get('pandas')], ['numpy', rec['software'].get('numpy')], ['NEXUS version', rec['software'].get('nexus_app')]])}
<p class="muted">Generated by NEXUS AI. Metrics are estimates from a single split and do not guarantee future performance.</p>
</main></body></html>"""
