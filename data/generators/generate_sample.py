"""Regenerate the SYNTHETIC sample dataset and test fixtures (deterministic).

Usage (from the repository root):
    PYTHONPATH=backend python data/generators/generate_sample.py [--rows 2000] [--seed 42]
"""

import argparse
from pathlib import Path

from app.ml.ingest import to_safe_csv
from app.ml.synthetic import (
    COLUMN_DEFINITIONS,
    generate_accounts,
    make_drift_fixture,
    make_quality_fixture,
)

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "data" / "sample"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--rows", type=int, default=2000)
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--anomaly-rate", type=float, default=0.02)
    args = ap.parse_args()

    df, truth = generate_accounts(args.rows, args.seed, args.anomaly_rate)
    (OUT / "fixtures").mkdir(parents=True, exist_ok=True)
    (OUT / "nexus_synthetic_accounts.csv").write_text(to_safe_csv(df), encoding="utf-8")
    (OUT / "anomaly_ground_truth.csv").write_text(truth.to_csv(index=False), encoding="utf-8")
    (OUT / "fixtures" / "quality_issues.csv").write_text(to_safe_csv(make_quality_fixture(df.head(400))), encoding="utf-8")
    (OUT / "fixtures" / "drift_current.csv").write_text(to_safe_csv(make_drift_fixture(df)), encoding="utf-8")

    lines = [
        "# Data card: NEXUS synthetic accounts\n",
        "**SYNTHETIC DATA.** Generated by `data/generators/generate_sample.py` from simple probabilistic rules. "
        "No real person, company or transaction is represented, and no external data was used.\n",
        f"- rows: {args.rows}, seed: {args.seed}, injected anomaly rate: {args.anomaly_rate}\n",
        "- `anomaly_ground_truth.csv` marks the injected anomalies and is deliberately kept out of the feature file.\n",
        "- `fixtures/quality_issues.csv`: missing values, 10 invalid numeric entries, 5 unexpected `region` values, 15 duplicate rows.\n",
        "- `fixtures/drift_current.csv`: shifted usage hours (x1.6), tickets (+2), plan mix and a new region `Overseas`.\n",
        "\n## Columns\n",
    ]
    lines += [f"- `{k}`: {v}\n" for k, v in COLUMN_DEFINITIONS.items()]
    lines.append(
        "\n## Caveats\n- Relationships (e.g. tickets raising churn probability) are written into the generator, "
        "so model performance on this data says nothing about real-world performance.\n"
    )
    (OUT / "DATA_CARD.md").write_text("".join(lines), encoding="utf-8")
    print(f"wrote sample data to {OUT}")


if __name__ == "__main__":
    main()
